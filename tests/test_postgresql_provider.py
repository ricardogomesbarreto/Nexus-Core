from unittest.mock import MagicMock

import psycopg
import pytest

from nexus.database.errors import (
    DatabaseConnectionError,
    DatabaseLifecycleError,
    DatabaseOperationError,
)
from nexus.database.postgresql import PostgreSQLProvider


def build_provider(password="secret"):
    return PostgreSQLProvider(
        host="127.0.0.1",
        port=5432,
        database="nexus",
        user="nexus",
        password=password,
        connect_timeout=5,
    )


def test_construction_does_not_connect(monkeypatch):
    def forbidden_connect(**kwargs):
        raise AssertionError("construction must not connect")

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        forbidden_connect,
    )

    provider = build_provider()

    assert provider.provider_id == "postgresql"
    assert provider.initialized is False


def test_initialize_connects_with_explicit_parameters(monkeypatch):
    connection = MagicMock()
    calls = []

    def fake_connect(**kwargs):
        calls.append(kwargs)
        return connection

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        fake_connect,
    )

    provider = build_provider(password="test-password")
    provider.initialize()

    assert provider.initialized is True
    assert calls == [
        {
            "host": "127.0.0.1",
            "port": 5432,
            "dbname": "nexus",
            "user": "nexus",
            "password": "test-password",
            "connect_timeout": 5,
        }
    ]


def test_initialize_rejects_double_initialization(monkeypatch):
    connection = MagicMock()

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        lambda **kwargs: connection,
    )

    provider = build_provider()
    provider.initialize()

    with pytest.raises(
        DatabaseLifecycleError,
        match="já foi inicializado",
    ):
        provider.initialize()


def test_initialize_maps_connection_error_without_password(monkeypatch):
    password = "never-expose-this-password"

    def failing_connect(**kwargs):
        raise psycopg.OperationalError(
            "simulated connection failure"
        )

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        failing_connect,
    )

    provider = build_provider(password=password)

    with pytest.raises(DatabaseConnectionError) as exc_info:
        provider.initialize()

    assert str(exc_info.value) == (
        "Falha ao conectar ao PostgreSQL"
    )
    assert password not in str(exc_info.value)
    assert provider.initialized is False


