def test_healthcheck_executes_select_one(monkeypatch):
    connection = MagicMock()
    schema_cursor = MagicMock()
    health_cursor = MagicMock()

    connection.cursor.return_value.__enter__.side_effect = [
        schema_cursor,
        health_cursor,
    ]
    health_cursor.fetchone.return_value = (1,)

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        lambda **kwargs: connection,
    )

    provider = build_provider()
    provider.initialize()

    assert provider.healthcheck() is True
    health_cursor.execute.assert_called_once_with("SELECT 1")


def test_close_is_idempotent(monkeypatch):
    connection = MagicMock()

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        lambda **kwargs: connection,
    )

    provider = build_provider()
    provider.initialize()

    provider.close()
    provider.close()

    connection.close.assert_called_once_with()
    assert provider.initialized is False

def test_initialize_creates_system_events_schema(monkeypatch):
    connection = MagicMock()
    cursor = MagicMock()

    connection.cursor.return_value.__enter__.return_value = cursor

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        lambda **kwargs: connection,
    )

    provider = build_provider()
    provider.initialize()

    executed_sql = cursor.execute.call_args.args[0]

    assert "CREATE TABLE IF NOT EXISTS system_events" in executed_sql
    assert (
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        in executed_sql
    )
    assert "event_type TEXT NOT NULL" in executed_sql
    assert "message TEXT NOT NULL" in executed_sql
    assert (
        "created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP"
        in executed_sql
    )
    connection.commit.assert_called_once_with()


def test_initialize_rolls_back_and_closes_when_schema_creation_fails(
    monkeypatch,
):
    connection = MagicMock()
    cursor = MagicMock()

    connection.cursor.return_value.__enter__.return_value = cursor
    cursor.execute.side_effect = psycopg.ProgrammingError(
        "simulated schema failure"
    )

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        lambda **kwargs: connection,
    )

    provider = build_provider()

    with pytest.raises(
        DatabaseOperationError,
        match="inicializar schema",
    ):
        provider.initialize()

    connection.rollback.assert_called_once_with()
    connection.close.assert_called_once_with()
    assert provider.initialized is False


