def test_add_event_uses_parameter_binding_and_commits(monkeypatch):
    connection = MagicMock()
    schema_cursor = MagicMock()
    event_cursor = MagicMock()

    connection.cursor.return_value.__enter__.side_effect = [
        schema_cursor,
        event_cursor,
    ]

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        lambda **kwargs: connection,
    )

    provider = build_provider()
    provider.initialize()

    provider.add_event(
        "system.start",
        "Nexus Core inicializado",
    )

    event_cursor.execute.assert_called_once_with(
        """
            INSERT INTO system_events (event_type, message)
            VALUES (%s, %s)
            """,
        (
            "system.start",
            "Nexus Core inicializado",
        ),
    )

    assert connection.commit.call_count == 2


def test_add_event_rolls_back_on_database_error(monkeypatch):
    connection = MagicMock()
    schema_cursor = MagicMock()
    event_cursor = MagicMock()

    connection.cursor.return_value.__enter__.side_effect = [
        schema_cursor,
        event_cursor,
    ]

    event_cursor.execute.side_effect = psycopg.DatabaseError(
        "simulated insert failure"
    )

    monkeypatch.setattr(
        "nexus.database.postgresql.psycopg.connect",
        lambda **kwargs: connection,
    )

    provider = build_provider()
    provider.initialize()

    with pytest.raises(
        DatabaseOperationError,
        match="persistir evento",
    ):
        provider.add_event(
            "system.start",
            "Nexus Core inicializado",
        )

    connection.rollback.assert_called_once_with()









