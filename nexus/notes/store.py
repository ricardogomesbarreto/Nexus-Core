"""Anotações Markdown locais. Nenhuma conversa é salva como nota automaticamente."""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from threading import RLock

import psycopg

from nexus.config.settings import Settings
from nexus.database.errors import DatabaseConfigurationError, DatabaseLifecycleError


class NoteError(RuntimeError):
    """Erro sanitizado de armazenamento ou validação."""


@dataclass(frozen=True)
class Note:
    id: int
    title: str
    body: str
    updated_at: datetime

    @classmethod
    def from_row(cls, row):
        return cls(int(row[0]), row[1], row[2], row[3])


class PostgreSQLNotes:
    """CRUD limitado, texto privado e índice de pesquisa sem serviço adicional."""

    MAX_TITLE = 120
    MAX_BODY = 16_000
    MAX_RESULTS = 50

    def __init__(self, settings: Settings):
        if settings.database_provider != "postgresql" or settings.database_host not in (
            "127.0.0.1", "localhost", "::1"
        ) or not settings.database_password:
            raise DatabaseConfigurationError("Anotações exigem PostgreSQL local configurado.")
        self._settings = settings
        self._connection = None
        self._lock = RLock()

    @staticmethod
    def _text(value, limit, label):
        if not isinstance(value, str) or not value.strip() or "\x00" in value or len(value) > limit:
            raise NoteError(f"{label} inválido ou acima do limite.")
        return value.strip()

    @staticmethod
    def _id(value):
        if type(value) is not int or value <= 0:
            raise NoteError("Identificador de anotação inválido.")
        return value

    @classmethod
    def _limit(cls, value):
        if type(value) is not int or not 1 <= value <= cls.MAX_RESULTS:
            raise NoteError("Limite de anotações inválido (1 a 50).")
        return value

    def initialize(self):
        with self._lock:
            if self._connection is not None:
                raise DatabaseLifecycleError("Anotações já inicializadas.")
            s = self._settings
            try:
                conn = psycopg.connect(
                    host=s.database_host, port=s.database_port, dbname=s.database_name,
                    user=s.database_user, password=s.database_password,
                    connect_timeout=s.database_connect_timeout,
                )
            except psycopg.Error as exc:
                raise NoteError("PostgreSQL local indisponível para anotações.") from exc
            try:
                with conn.cursor() as cursor:
                    cursor.execute("""
                        CREATE TABLE IF NOT EXISTS nexus_notes (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
                            body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 16000),
                            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                        )
                    """)
                    cursor.execute("""
                        CREATE INDEX IF NOT EXISTS nexus_notes_fts_idx
                        ON nexus_notes USING GIN
                        (to_tsvector('simple', title || ' ' || body))
                    """)
                conn.commit()
            except psycopg.Error as exc:
                conn.rollback()
                conn.close()
                raise NoteError("Falha ao preparar anotações locais.") from exc
            self._connection = conn

    def close(self):
        with self._lock:
            if self._connection is not None:
                self._connection.close()
                self._connection = None

    def _run(self, callback):
        with self._lock:
            if self._connection is None:
                raise DatabaseLifecycleError("Anotações não inicializadas.")
            try:
                with self._connection.cursor() as cursor:
                    result = callback(cursor)
                self._connection.commit()
                return result
            except psycopg.Error as exc:
                self._connection.rollback()
                raise NoteError("Falha na operação de anotações PostgreSQL.") from exc
            except Exception:
                self._connection.rollback()
                raise

    def create(self, title: str, body: str) -> Note:
        title = self._text(title, self.MAX_TITLE, "Título")
        body = self._text(body, self.MAX_BODY, "Texto")

        def action(cursor):
            cursor.execute(
                "INSERT INTO nexus_notes (title, body) VALUES (%s, %s) "
                "RETURNING id, title, body, updated_at", (title, body),
            )
            return Note.from_row(cursor.fetchone())
        return self._run(action)

    def update(self, note_id: int, title: str, body: str) -> Note | None:
        note_id = self._id(note_id)
        title = self._text(title, self.MAX_TITLE, "Título")
        body = self._text(body, self.MAX_BODY, "Texto")

        def action(cursor):
            cursor.execute(
                "UPDATE nexus_notes SET title = %s, body = %s, "
                "updated_at = CURRENT_TIMESTAMP WHERE id = %s "
                "RETURNING id, title, body, updated_at", (title, body, note_id),
            )
            row = cursor.fetchone()
            return Note.from_row(row) if row else None
        return self._run(action)

    def get(self, note_id: int) -> Note | None:
        def action(cursor):
            cursor.execute(
                "SELECT id, title, body, updated_at FROM nexus_notes WHERE id = %s",
                (self._id(note_id),),
            )
            row = cursor.fetchone()
            return Note.from_row(row) if row else None
        return self._run(action)

    def list(self, limit: int = 20) -> list[Note]:
        limit = self._limit(limit)

        def action(cursor):
            cursor.execute("SELECT id, title, body, updated_at FROM nexus_notes "
                           "ORDER BY updated_at DESC, id DESC LIMIT %s", (limit,))
            return [Note.from_row(row) for row in cursor.fetchall()]
        return self._run(action)

    def search(self, query: str, limit: int = 20) -> list[Note]:
        query = self._text(query, 160, "Pesquisa")
        limit = self._limit(limit)

        def action(cursor):
            cursor.execute("SELECT id, title, body, updated_at FROM nexus_notes "
                           "WHERE to_tsvector('simple', title || ' ' || body) "
                           "@@ plainto_tsquery('simple', %s) "
                           "ORDER BY updated_at DESC, id DESC LIMIT %s", (query, limit))
            return [Note.from_row(row) for row in cursor.fetchall()]
        return self._run(action)

    def delete(self, note_id: int) -> bool:
        def action(cursor):
            cursor.execute("DELETE FROM nexus_notes WHERE id = %s", (self._id(note_id),))
            return cursor.rowcount > 0
        return self._run(action)
