"""Cartões de estudo ligados a trechos importados, somente em PostgreSQL local.

Não gera perguntas, lê diretórios ou inicia modelos. A exclusão do documento
remove automaticamente os cartões associados. A resposta deve constar no
trecho de origem; o usuário decide o que perguntar e quando revisar.
"""

from dataclasses import dataclass
from datetime import datetime
from threading import RLock

import psycopg

from nexus.config.settings import Settings
from nexus.database.errors import DatabaseConfigurationError, DatabaseLifecycleError


class StudyError(RuntimeError):
    """Erro público sem conteúdo de documentos ou credenciais."""


@dataclass(frozen=True)
class StudyCard:
    id: int
    source_chunk_id: int
    source_name: str
    question: str
    answer: str
    source_excerpt: str
    box: int
    due_at: datetime
    review_count: int


class PostgreSQLStudyCards:
    """Revisão voluntária com estado pequeno e limitado por cartão."""

    MAX_QUESTION = 240
    MAX_ANSWER = 1000
    MAX_DUE = 20

    def __init__(self, settings: Settings):
        if (settings.database_provider != "postgresql"
                or settings.database_host not in ("127.0.0.1", "localhost", "::1")
                or not settings.database_password):
            raise DatabaseConfigurationError("Estudo exige PostgreSQL local configurado.")
        self._settings = settings
        self._connection = None
        self._lock = RLock()

    def initialize(self) -> None:
        with self._lock:
            if self._connection is not None:
                raise DatabaseLifecycleError("Estudo já inicializado.")
            s = self._settings
            try:
                connection = psycopg.connect(
                    host=s.database_host, port=s.database_port,
                    dbname=s.database_name, user=s.database_user,
                    password=s.database_password,
                    connect_timeout=s.database_connect_timeout,
                )
            except psycopg.Error as exc:
                raise StudyError("PostgreSQL local indisponível para estudo.") from exc
            try:
                with connection.cursor() as cursor:
                    cursor.execute("""
                        CREATE TABLE IF NOT EXISTS nexus_study_cards (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            chunk_id BIGINT NOT NULL REFERENCES nexus_knowledge_chunks(id)
                                ON DELETE CASCADE,
                            question TEXT NOT NULL CHECK (char_length(question) BETWEEN 1 AND 240),
                            answer TEXT NOT NULL CHECK (char_length(answer) BETWEEN 1 AND 1000),
                            box SMALLINT NOT NULL DEFAULT 1 CHECK (box BETWEEN 1 AND 5),
                            due_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            review_count INTEGER NOT NULL DEFAULT 0 CHECK (review_count >= 0),
                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            UNIQUE (chunk_id, question)
                        )
                    """)
                    cursor.execute("CREATE INDEX IF NOT EXISTS nexus_study_due_idx "
                                   "ON nexus_study_cards (due_at, id)")
                    cursor.execute("""
                        CREATE TABLE IF NOT EXISTS nexus_study_sessions (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            chunk_id BIGINT NOT NULL REFERENCES nexus_knowledge_chunks(id)
                                ON DELETE CASCADE,
                            correct SMALLINT NOT NULL CHECK (correct BETWEEN 0 AND 10),
                            total SMALLINT NOT NULL CHECK (total BETWEEN 1 AND 10),
                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            CHECK (correct <= total)
                        )
                    """)
                    cursor.execute("CREATE INDEX IF NOT EXISTS nexus_study_sessions_recent_idx "
                                   "ON nexus_study_sessions (id DESC)")

                connection.commit()
            except psycopg.Error as exc:
                connection.rollback()
                connection.close()
                raise StudyError("Prepare a biblioteca local antes dos cartões de estudo.") from exc
            self._connection = connection

    def close(self) -> None:
        with self._lock:
            if self._connection is not None:
                self._connection.close()
                self._connection = None

    @staticmethod
    def _id(value) -> int:
        if type(value) is not int or value < 1:
            raise StudyError("Identificador de estudo inválido.")
        return value

    @staticmethod
    def _text(value, maximum: int, label: str) -> str:
        if (not isinstance(value, str) or not value.strip() or "\x00" in value
                or len(value.strip()) > maximum):
            raise StudyError(f"{label} inválida ou acima do limite.")
        return value.strip()

    @staticmethod
    def _normal(text: str) -> str:
        return " ".join(text.split()).casefold()

    def _run(self, callback):
        with self._lock:
            if self._connection is None:
                raise DatabaseLifecycleError("Estudo não inicializado.")
            try:
                with self._connection.cursor() as cursor:
                    result = callback(cursor)
                self._connection.commit()
                return result
            except psycopg.Error as exc:
                self._connection.rollback()
                raise StudyError("Falha na operação de estudo PostgreSQL.") from exc
            except Exception:
                self._connection.rollback()
                raise

    @staticmethod
    def _card(row) -> StudyCard:
        return StudyCard(id=int(row[0]), source_chunk_id=int(row[1]),
                         source_name=row[2], question=row[3], answer=row[4],
                         source_excerpt=row[5], box=int(row[6]),
                         due_at=row[7], review_count=int(row[8]))

    _SELECT = ("SELECT s.id, s.chunk_id, d.name, s.question, s.answer, "
               "c.body, s.box, s.due_at, s.review_count "
               "FROM nexus_study_cards s "
               "JOIN nexus_knowledge_chunks c ON c.id = s.chunk_id "
               "JOIN nexus_knowledge_documents d ON d.id = c.document_id ")

    def create(self, chunk_id: int, question: str, answer: str) -> StudyCard:
        chunk_id = self._id(chunk_id)
        question = self._text(question, self.MAX_QUESTION, "Pergunta")
        answer = self._text(answer, self.MAX_ANSWER, "Resposta")

        def action(cursor):
            cursor.execute("SELECT body FROM nexus_knowledge_chunks WHERE id = %s FOR SHARE",
                           (chunk_id,))
            row = cursor.fetchone()
            if row is None:
                raise StudyError("Trecho da biblioteca não encontrado.")
            if self._normal(answer) not in self._normal(row[0]):
                raise StudyError("A resposta deve constar no trecho selecionado.")
            cursor.execute("INSERT INTO nexus_study_cards (chunk_id, question, answer) "
                           "VALUES (%s, %s, %s) RETURNING id",
                           (chunk_id, question, answer))
            card_id = cursor.fetchone()[0]
            cursor.execute(self._SELECT + "WHERE s.id = %s", (card_id,))
            return self._card(cursor.fetchone())
        return self._run(action)

    def due(self, limit: int = 10) -> list[StudyCard]:
        if type(limit) is not int or not 1 <= limit <= self.MAX_DUE:
            raise StudyError("Limite de revisão inválido.")

        def action(cursor):
            cursor.execute(self._SELECT + "WHERE s.due_at <= CURRENT_TIMESTAMP "
                           "ORDER BY s.due_at, s.id LIMIT %s", (limit,))
            return [self._card(row) for row in cursor.fetchall()]
        return self._run(action)

    def grade(self, card_id: int, correct: bool) -> bool:
        card_id = self._id(card_id)
        if type(correct) is not bool:
            raise StudyError("Resultado de revisão inválido.")

        def action(cursor):
            cursor.execute("""
                UPDATE nexus_study_cards SET
                    box = CASE WHEN %s THEN LEAST(box + 1, 5) ELSE 1 END,
                    due_at = CURRENT_TIMESTAMP + CASE WHEN %s
                        THEN make_interval(days => CASE box
                            WHEN 1 THEN 1 WHEN 2 THEN 3 WHEN 3 THEN 7
                            ELSE 14 END)
                        ELSE INTERVAL '10 minutes' END,
                    review_count = review_count + 1
                WHERE id = %s AND due_at <= CURRENT_TIMESTAMP
                RETURNING id
            """, (correct, correct, card_id))
            return cursor.fetchone() is not None
        return self._run(action)

    def delete(self, card_id: int) -> bool:
        card_id = self._id(card_id)

        def action(cursor):
            cursor.execute("DELETE FROM nexus_study_cards WHERE id = %s", (card_id,))
            return cursor.rowcount == 1
        return self._run(action)

    def record_session(self, chunk_id: int, correct: int, total: int) -> int:
        """Salvar resultado por escolha explícita; nunca registra respostas ou áudio."""
        chunk_id = self._id(chunk_id)
        if (type(correct) is not int or type(total) is not int
                or not 1 <= total <= 10 or not 0 <= correct <= total):
            raise StudyError("Resultado de sessão inválido.")

        def action(cursor):
            cursor.execute(
                "INSERT INTO nexus_study_sessions (chunk_id, correct, total) "
                "SELECT id, %s, %s FROM nexus_knowledge_chunks WHERE id = %s "
                "RETURNING id", (correct, total, chunk_id),
            )
            row = cursor.fetchone()
            if row is None:
                raise StudyError("Trecho de origem não encontrado.")
            # Conservar somente 200 sessões do usuário local; sem respostas.
            cursor.execute(
                "DELETE FROM nexus_study_sessions WHERE id IN "
                "(SELECT id FROM nexus_study_sessions ORDER BY id DESC OFFSET 200)"
            )
            return int(row[0])
        return self._run(action)

    def recent_sessions(self, limit: int = 10) -> list[tuple[int, int, int]]:
        if type(limit) is not int or not 1 <= limit <= 20:
            raise StudyError("Limite de histórico inválido.")

        def action(cursor):
            cursor.execute(
                "SELECT chunk_id, correct, total FROM nexus_study_sessions "
                "ORDER BY id DESC LIMIT %s", (limit,),
            )
            return [(int(chunk), int(correct), int(total))
                    for chunk, correct, total in cursor.fetchall()]
        return self._run(action)
